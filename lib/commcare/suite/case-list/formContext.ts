import {
	type BlueprintDoc,
	type Module,
	tileCell,
	type Uuid,
} from "@/lib/domain";
import {
	caseContextLine,
	resolveCaseFormContext,
} from "@/lib/domain/caseFormContext";
import { el, xel } from "../../elementBuilders";
import type { ModuleExpressionContexts } from "../../expressionContext";
import type { LookupWireNaming } from "../../lookup/naming";
import { toWire, type WireTermBindings } from "../../xpath/wire/fromExpression";
import { InstanceSink } from "../../xpath/wire/instances";
import { buildTileStyleBlock } from "./tileStyle";

export function caseContextDetailIds(
	doc: BlueprintDoc,
	moduleUuid: Uuid,
	indexOf: (uuid: Uuid) => number,
): { persistentDetailId?: string; inlineDetailId?: string } {
	const use = resolveCaseFormContext(doc.modules, moduleUuid);
	if (!use) return {};
	const owner = indexOf(use.sourceModuleUuid);
	return {
		persistentDetailId: `m${owner}_${use.kind === "tile" ? "case_short" : "persistent_case_context"}`,
		...(use.inlineModuleUuid && {
			inlineDetailId: `m${indexOf(use.inlineModuleUuid)}_case_long`,
		}),
	};
}

/** The one centred field generated by HQ's _get_persistent_case_context_detail. */
export function caseContextLineDetail(
	mod: Module,
	index: number,
	expressions: ModuleExpressionContexts,
	lookupNaming?: LookupWireNaming,
	bindings?: WireTermBindings,
) {
	const context = mod.caseListConfig?.contextAboveForm;
	const expression = caseContextLine(context);
	if (!expression) return;
	// HQ's build writes no line where the short detail is a tile whose persistence is on
	// (`suite_xml/sections/details.py::get_section_elements`): its own tile persisting, or
	// another menu's tile expanded above the forms, beside which the HQ JSON switches this
	// menu's persistence on (`hqJson/caseList.ts`).
	const tile = mod.caseListConfig?.tile;
	if (
		tile !== undefined &&
		(tile.persistOnForms === true ||
			(context?.kind === "menu-tile" && context.expandDetails === true))
	)
		return;
	const instances = new InstanceSink();
	const value = toWire(expression, {
		target: "suite",
		root: "casedb",
		types: expressions({ slot: "case_form_context_line" }),
		bindings: {
			...bindings,
			...(lookupNaming && {
				lookup: { naming: lookupNaming, instanceScope: "suite" },
			}),
		},
	});
	const centered = buildTileStyleBlock(
		tileCell(0, 0, 12, 1, {
			horizontalAlign: "center",
			fontSize: "large",
			showBorder: false,
			showShading: false,
		}),
	);
	// A context line leaves its vertical alignment to the native reader.
	delete centered.attribs["vert-align"];
	const element = el("detail", { id: `m${index}_persistent_case_context` }, [
		el("title", {}, [el("text", {})]),
		el("field", {}, [
			centered,
			el("header", {}, [el("text", {})]),
			el("template", {}, [
				el("text", {}, [
					xel(
						"xpath",
						{ xpath: { function: value } },
						{ mode: { target: "suite" }, instances },
					),
				]),
			]),
		]),
	]);
	return { element, instances: instances.declarations() };
}
